    def test_data_parity_diagnostics_completeness(self):
        """Diagnostics accurately record observed vs imputed features, age top-coding, and condition parsing."""
        patient_data = {
            "age": 90,  # Should be top-coded to 85.0 for MEPS training distribution parity
            "gender": "female",
            "diseaseInput": "hypertension and asthma"
        }
        res = calculate_risk(patient_data)
        diag = res["data_parity_diagnostics"]

        assert diag["age_representation_parity"]["intake_age"] == 90
        assert diag["age_representation_parity"]["model_encoded_age"] == 85.0
        assert diag["age_representation_parity"]["is_top_coded_meps"] is True

        # For observable models with text input:
        assert "age" in diag["features_observed"]
        assert "gender" in diag["features_observed"]
        assert "diseaseInput" in diag["features_observed"]
        assert len(diag["features_imputed"]) == 0 or "perceived_health" in diag["features_imputed"]

        # Output keys distinguish ranking score, dollar spending, and probability
        assert "relative_expenditure_score" in res
        assert "expected_annual_dollar_expenditure" in res
        assert "high_cost_probability" in res
        assert "premium" in res
        assert "simulated_loss_percentiles" in res

    def test_auxiliary_benchmark_distribution_integrity_and_hash_match(self, manifest_bundle):
        """Benchmark cost distribution artifact matches manifest SHA-256 and loads safely."""
        manifest, verified = manifest_bundle
        auxiliary = manifest.get("auxiliary_artifacts", {})
        assert "benchmark_distribution" in auxiliary
        bench_spec = auxiliary["benchmark_distribution"]

        assert "benchmark_distribution" in verified
        bench_info = verified["benchmark_distribution"]
        assert os.path.exists(bench_info["path"])

        with open(bench_info["path"], "rb") as f:
            actual_hash = hashlib.sha256(f.read()).hexdigest()

        assert actual_hash.lower() == bench_spec["sha256"].lower()
        bench_data = bench_info["data"]
        assert isinstance(bench_data, dict)
        assert "predicted_costs_oof" in bench_data
        assert len(bench_data["predicted_costs_oof"]) > 1000

