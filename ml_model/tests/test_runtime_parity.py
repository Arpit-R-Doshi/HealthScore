class TestRuntimeParityAndModelManifest:
    """Verifies production inference uses approved artifacts, correct feature schemas, and matching predictions."""

    @pytest.fixture(scope="class")
    @classmethod
    def manifest_bundle(cls):
        """Loads and verifies the canonical manifest."""
        manifest, verified = load_and_verify_manifest(MANIFEST_PATH)
        return manifest, verified

    def test_approved_models_exist_and_hashes_match(self, manifest_bundle):
        """Every production model in the manifest exists on disk and has an exact SHA-256 match."""
        manifest, verified = manifest_bundle
        approved = manifest["approved_models"]

        assert "relative_expenditure_ranker" in approved
        assert "direct_dollar_regressor" in approved
        assert "high_cost_classifier" in approved

        for model_key, spec in approved.items():
            info = verified[model_key]
            assert os.path.exists(info["path"]), f"Artifact {info['path']} missing"

            with open(info["path"], "rb") as f:
                actual_hash = hashlib.sha256(f.read()).hexdigest()

            assert actual_hash.lower() == spec["sha256"].lower(), (
                f"Hash mismatch for {model_key}: manifest={spec['sha256']} actual={actual_hash}"
            )

    def test_production_feature_columns_and_order(self, manifest_bundle):
        """All three approved models use exactly the 11 observable feature columns in identical order."""
        manifest, verified = manifest_bundle
        expected_schema = list(OBSERVABLE_COLS)
        assert len(expected_schema) == 11

        for model_key in manifest["approved_models"]:
            info = verified[model_key]
            model = info["model"]
            spec = info["spec"]

            assert spec["feature_count"] == 11
            assert spec["feature_schema"] == expected_schema
            assert model.n_features_in_ == 11

            if hasattr(model, "feature_names_in_"):
                model_cols = [str(c) for c in model.feature_names_in_]
                assert model_cols == expected_schema, (
                    f"Feature ordering mismatch in {model_key}: {model_cols} vs {expected_schema}"
                )

    def test_classifier_target_definition_and_locked_threshold(self, manifest_bundle):
        """The high-cost classifier is verified as Target 2 with the locked $17,827.41 threshold."""
        manifest, verified = manifest_bundle
        cls_spec = manifest["approved_models"]["high_cost_classifier"]

        assert cls_spec["intended_runtime_role"] == "high_expenditure_classification"
        assert cls_spec["target_name"] == "Target 2: Survey-Weighted Population Top Decile"
        assert abs(cls_spec["target_threshold_dollars"] - 17827.405977383045) < 1e-4
        assert cls_spec["weighting_policy"] == "normalized_person_weights"

    def test_direct_artifact_parity_with_controlled_fixtures(self, manifest_bundle):
        """Predictions generated by calculate_risk match direct calls on approved model artifacts."""
        _, verified = manifest_bundle
        ranker = verified["relative_expenditure_ranker"]["model"]
        tweedie = verified["direct_dollar_regressor"]["model"]
        classifier = verified["high_cost_classifier"]["model"]

        test_patients = [
            {"age": 25, "gender": "female", "diseaseInput": "no medical problems"},
            {"age": 55, "gender": "male", "diseaseInput": "hypertension, type 2 diabetes"},
            {"age": 72, "gender": "female", "diseaseInput": "history of stroke, arthritis, asthma"}
        ]

        for p_data in test_patients:
            engine_res = calculate_risk(p_data)

            # Build direct observable feature frame
            age_model = min(float(p_data["age"]), 85.0)
            gender_male = 1 if p_data["gender"] == "male" else 0
            flags = risk_engine.parse_clinical_conditions(p_data["diseaseInput"])
            cardio, metabolic, resp, onco, msk, psych = flags
            n_comorb = sum(1 for v in flags if v > 0)

            direct_df = pd.DataFrame([{
                'AGE23X': age_model,
                'Gender_Male': gender_male,
                'Cardio_ACG': cardio,
                'Metabolic_ACG': metabolic,
                'Respiratory_ACG': resp,
                'Oncology_ACG': onco,
                'Musculoskeletal_ACG': msk,
                'Psychiatric_ACG': psych,
                'Comorbidity_Count': n_comorb,
                'Multimorbidity_Penalty': n_comorb ** 2,
                'Age_x_Comorbidity': age_model * n_comorb
            }])[OBSERVABLE_COLS]

            # Direct predictions
            direct_pred_log = float(ranker.predict(direct_df)[0])
            direct_exp_dollar = round(float(max(0.0, tweedie.predict(direct_df)[0])), 2)
            direct_prob = round(float(classifier.predict_proba(direct_df)[0, 1]), 4)

            # Verify parity
            assert round(float(np.expm1(direct_pred_log)), 2) == engine_res["ranking_expenditure_expm1"]
            assert direct_exp_dollar == engine_res["expected_annual_dollar_expenditure"]
            assert direct_prob == engine_res["high_cost_probability"]

    def test_fail_closed_on_manifest_hash_mismatch(self):
        """load_and_verify_manifest raises RuntimeError and fails closed when hash mismatches."""
        with open(MANIFEST_PATH, "r") as f:
            manifest = json.load(f)

        tampered = dict(manifest)
        tampered["approved_models"]["relative_expenditure_ranker"]["sha256"] = "0" * 64

        with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as tf:
            json.dump(tampered, tf)
            temp_path = tf.name

        try:
            with pytest.raises(RuntimeError, match="Artifact hash mismatch"):
                load_and_verify_manifest(temp_path)
        finally:
            if os.path.exists(temp_path):
                os.unlink(temp_path)

